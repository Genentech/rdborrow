pr <- function(m, ...) {
  rr <- w(run_analysis(mk(m, ...)))
  if (!is.null(rr)) {
    print(rr$results)
    cat("borrow_weight:", rr$borrow_weight, "\n")
  }
  invisible(rr)
}
