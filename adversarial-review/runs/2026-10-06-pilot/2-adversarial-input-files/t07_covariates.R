d <- SyntheticData
d$const <- 1
cat("== constant covariate in PS and outcome formulas\n")
try_show(ra(ec_ipw("S ~ x1 + x5 + const"), d, x = c("x1", "x5", "const")))
try_show(ra(ec_ipw("S ~ x1 + x5"), d, x = c("x1", "x5", "const")))
try_show(ra(ec_aipw("S ~ x1 + x5 + const", c("y1 ~ x1 + x5 + const", "y2 ~ x1 + x5 + const")), d, x = c("x1", "x5", "const")))
cat("== one-level factor covariate\n")
d$f1 <- factor("a")
try_show(ra(ec_ipw("S ~ x1 + f1"), d, x = c("x1", "f1")))
cat("== factor covariate (3 levels) vs equivalent dummies\n")
set.seed(7)
d$f3 <- factor(sample(c("a", "b", "c"), nrow(d), TRUE))
d$fb <- as.numeric(d$f3 == "b")
d$fc <- as.numeric(d$f3 == "c")
r_f <- try_show(ra(ec_aipw("S ~ x1 + f3", c("y1 ~ x1 + f3", "y2 ~ x1 + f3")), d, x = c("x1", "f3")))
r_d <- try_show(ra(ec_aipw("S ~ x1 + fb + fc", c("y1 ~ x1 + fb + fc", "y2 ~ x1 + fb + fc")), d, x = c("x1", "fb", "fc")))
cat("  max diff factor vs dummies:", max(abs(as.matrix(r_f$results) - as.matrix(r_d$results))), "\n")
cat("== character covariate\n")
d$c3 <- as.character(d$f3)
r_c <- try_show(ra(ec_aipw("S ~ x1 + c3", c("y1 ~ x1 + c3", "y2 ~ x1 + c3")), d, x = c("x1", "c3")))
cat("  max diff char vs dummies:", max(abs(as.matrix(r_c$results) - as.matrix(r_d$results))), "\n")
cat("== factor level present only among trial treated (absent from all controls)\n")
d$g <- factor(ifelse(seq_len(nrow(d)) %in% which(d$S == 1 & d$A == 1)[1:5], "rare", "common"))
try_show(ra(ec_ipw("S ~ x1 + g"), d, x = c("x1", "g")))
try_show(ra(ec_aipw("S ~ x1 + g", c("y1 ~ x1 + g", "y2 ~ x1 + g")), d, x = c("x1", "g")))
cat("== numeric covariate constant among all controls (trial + external) but varying among treated\n")
d$h <- ifelse(d$A == 1, rnorm(nrow(d)), 0)
try_show(ra(ec_aipw("S ~ x1", c("y1 ~ x1 + h", "y2 ~ x1 + h")), d, x = c("x1", "h")))
cat("== covariate collinear with another (x6 = 2 * x5)\n")
d$x6 <- 2 * d$x5
try_show(ra(ec_ipw("S ~ x5 + x6"), d, x = c("x5", "x6")))
try_show(ra(ec_aipw("S ~ x5", c("y1 ~ x5 + x6", "y2 ~ x5 + x6")), d, x = c("x5", "x6")))
cat("== duplicated covariate name in covariates_col_name\n")
try_show(ra(ec_ipw("S ~ x1 + x5"), d, x = c("x1", "x5", "x5")))
cat("== covariate appears also as outcome\n")
try_show(ra(ec_ipw("S ~ x1 + x5"), d, y = c("y1", "x5"), x = c("x1", "x5")))
