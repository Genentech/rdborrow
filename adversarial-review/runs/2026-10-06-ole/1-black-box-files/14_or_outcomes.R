# did_ec_or(): what does outcome_col_name control?
source("/tmp/claude-1000/-home-matts-Documents-rdborrow/403de6d7-6cc1-4a41-9c33-1c39c7fb55db/scratchpad/review-ole/bb/setup.R")
y <- c("y1", "y2", "y3", "y4")
model_forms <- f5(y)
or <- did_ec_or(model_forms, model_forms, model_forms, bootstrap = 50)
ipw <- did_ec_ipw("S ~ x1 + x2 + x3 + x4 + x5", bootstrap = 50)
run <- function(m, outcomes, ...) {
  set.seed(1)
  print(show(suppressWarnings(ole(m, outcomes = outcomes, ...))))
}
cat("## did_ec_or, outcome_col_name y1..y4 (vignette)\n")
run(or, y)
cat("## did_ec_or, outcome_col_name y4, y3, y2, y1 with the same formulas\n")
run(or, rev(y))
cat("## did_ec_or, outcome_col_name x1, x2, x3, x4 (covariates!) with the same formulas\n")
run(or, c("x1", "x2", "x3", "x4"), cov = "x5")
cat("## did_ec_ipw, outcome_col_name y4, y3, y2, y1 (changes, as it should)\n")
run(ipw, rev(y))
cat("\n## did_ec_or, outcome_col_name y1..y3 (one OLE visit) with the 4-visit vignette formulas\n")
run(or, y[1:3])
cat("## did_ec_aipw, outcome_col_name y1..y3 with the 4-visit vignette formulas\n")
run(did_ec_aipw("S ~ x1 + x2 + x3 + x4 + x5", outcome_formula = model_forms, bootstrap = 50), y[1:3])
cat("## did_ec_or, outcome_col_name y1, y2, y4 (visit 3 dropped) with the 4-visit vignette formulas\n")
run(or, c("y1", "y2", "y4"))
